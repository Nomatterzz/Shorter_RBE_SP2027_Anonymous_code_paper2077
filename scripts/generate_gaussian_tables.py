#!/usr/bin/env python3
"""Certify 256-bit CDT thresholds using outward-rounded 896-bit intervals."""
import argparse,json,hashlib
from pathlib import Path
from certified_math import pi_interval,exp_negative_interval,ceildiv
if not __debug__:
    raise RuntimeError("Verification must not run with Python optimization enabled")
ROOT=Path(__file__).resolve().parents[1]
P,BITS=896,256

def table(s,half=False):
    T=12*s;pl,pu=pi_interval(P)
    w={x:exp_negative_interval(pl*x*x//(s*s),ceildiv(pu*x*x,s*s),P) for x in range(T+1)}
    support=list(range(0 if half else -T,T+1))
    Zl=sum(w[abs(x)][0] for x in support);Zu=sum(w[abs(x)][1] for x in support)
    lo=hi=0;unit=1<<BITS;values=[]
    for x in support[:-1]:
        a,b=w[abs(x)];lo+=a;hi+=b
        # Intersect CDF and strictly-positive survival-function enclosures.
        t0=max((lo<<BITS)//Zu,unit-ceildiv((Zu-hi)*unit,Zl))
        t1=min((hi<<BITS)//Zl,unit-max(1,ceildiv((Zl-lo)*unit,Zu)))
        if t0!=t1:raise ArithmeticError((s,x,'uncertified threshold'))
        values.append(f'{t0:064x}')
    return dict(sigma=s,half=half,offset=support[0],support_max=T,bits=BITS,thresholds=values)

def generate():
    ts={'full17':table(17),'full32':table(32),'half32':table(32,True)}
    pl,pu=pi_interval(P)
    h=['// Generated by scripts/generate_gaussian_tables.py. Do not edit.','#pragma once','#include "rbe/rbe.hpp"','namespace rbe::tables {',f'inline constexpr unsigned precision={P};',f'inline constexpr char pi_lo_hex[]="0x{pl:x}";',f'inline constexpr char pi_hi_hex[]="0x{pu:x}";']
    for name,t in ts.items():
        h.append(f'inline constexpr std::array<U256,{len(t["thresholds"])}> {name} = {{{{')
        for hexv in t['thresholds']:
            v=int(hexv,16);h.append(' U256{{'+', '.join(f'0x{(v>>(64*i))&((1<<64)-1):016x}ULL' for i in range(4))+'}},')
        h.append('}};')
    h+=['} // namespace rbe::tables',''];header='\n'.join(h)
    manifest=dict(format=1,interval_precision=P,threshold_bits=BITS,pi_interval_hex=[f'{pl:x}',f'{pu:x}'],generated_header_sha256=hashlib.sha256(header.encode()).hexdigest(),tables=ts)
    return header,json.dumps(manifest,indent=2,sort_keys=True)+'\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();h,m=generate()
    for path,data in {ROOT/'include/rbe/gaussian_tables.hpp':h,ROOT/'data/gaussian_tables.json':m}.items():
        if a.check:
            if path.read_text()!=data:raise SystemExit('mismatch: '+path.name)
        else:path.write_text(data)
    print(json.dumps(dict(certified=True,threshold_bits=BITS,interval_precision=P,check_only=a.check)))
if __name__=='__main__':main()
